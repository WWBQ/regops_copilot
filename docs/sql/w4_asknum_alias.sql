CREATE TABLE IF NOT EXISTS asknum_alias (
    id          BIGSERIAL PRIMARY KEY,
    kind        VARCHAR(16)  NOT NULL,
    alias       TEXT         NOT NULL,
    target      TEXT         NOT NULL,
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_asknum_alias_kind CHECK (kind IN ('concept', 'company')),
    CONSTRAINT uq_asknum_alias_kind_alias UNIQUE (kind, alias)
);

CREATE INDEX IF NOT EXISTS idx_asknum_alias_kind_enabled
    ON asknum_alias (kind, enabled);

